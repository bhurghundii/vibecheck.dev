"""Renders the Homebrew formula for the local `vibecheck` CLI (app/cli.py).

    python scripts/brew_formula.py --version 0.2.0 --sha256 <tarball sha256>

prints Formula/vibecheck.rb for the bhurghundii/homebrew-tap repo. The formula
builds from the GitHub tag tarball, and one `resource` per runtime dependency
comes from uv.lock, so the versions brew installs are the locked ones. Only the
project's own dependencies are followed, never the dependency groups, so the
server's packages stay out. The release workflow runs this on every tag.

Stdlib only, so it runs on a bare runner without `uv sync`.
"""

from __future__ import annotations

import argparse
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REPO = "bhurghundii/vibecheck.dev"
PROJECT = "vibecheck-dev"
PYTHON = "python@3.13"

_TEMPLATE = """\
# Generated by scripts/brew_formula.py in {repo}; edit that, not this.
class Vibecheck < Formula
  include Language::Python::Virtualenv

  desc "Quiz yourself on your own code change before it merges"
  homepage "https://github.com/{repo}"
  url "https://github.com/{repo}/archive/refs/tags/v{version}.tar.gz"
  sha256 "{sha256}"
  license "MIT"

  depends_on "{python}"
{resources}
  def install
    virtualenv_install_with_resources
  end

  test do
    assert_match "usage: vibecheck", shell_output("#{{bin}}/vibecheck --help")
    (testpath/"empty.diff").write ""
    output = shell_output("#{{bin}}/vibecheck --fake --diff #{{testpath}}/empty.diff 2>&1", 2)
    assert_match "No changes to ask about", output
  end
end
"""

_RESOURCE = """
  resource "{name}" do
    url "{url}"
    sha256 "{sha256}"
  end
"""


def _packages(lock: dict) -> dict[str, dict]:
    return {p["name"]: p for p in lock["package"]}


def runtime_closure(lock: dict, project: str = PROJECT) -> list[dict]:
    """Every package the project needs at runtime, sorted by name. Environment
    markers are ignored, so this can include a package only some Pythons need;
    installing it anyway is harmless."""
    packages = _packages(lock)
    seen: dict[str, dict] = {}
    pending = [(d["name"], d.get("extra", [])) for d in packages[project].get("dependencies", [])]
    while pending:
        name, extras = pending.pop()
        package = packages[name]
        deps = list(package.get("dependencies", []))
        for extra in extras:
            deps += package.get("optional-dependencies", {}).get(extra, [])
        if name not in seen:
            seen[name] = package
        pending += [(d["name"], d.get("extra", [])) for d in deps if d["name"] not in seen]
    return [seen[name] for name in sorted(seen)]


def render(lock: dict, *, version: str, sha256: str) -> str:
    resources = []
    for package in runtime_closure(lock):
        sdist = package.get("sdist")
        if not sdist:
            # Homebrew builds resources from source, so a wheel-only package can't go in.
            raise SystemExit(f"{package['name']} has no sdist in uv.lock")
        algo, _, digest = sdist["hash"].partition(":")
        if algo != "sha256":
            raise SystemExit(f"{package['name']}: expected a sha256 hash, got {algo}")
        resources.append(_RESOURCE.format(name=package["name"], url=sdist["url"], sha256=digest))
    return _TEMPLATE.format(
        repo=REPO, version=version, sha256=sha256, python=PYTHON, resources="".join(resources)
    )


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--version", required=True, help="e.g. 0.2.0 (no leading v)")
    parser.add_argument("--sha256", required=True, help="sha256 of the tag's .tar.gz")
    parser.add_argument("--lock", type=Path, default=ROOT / "uv.lock")
    args = parser.parse_args(argv)
    lock = tomllib.loads(args.lock.read_text())
    sys.stdout.write(render(lock, version=args.version.removeprefix("v"), sha256=args.sha256))


if __name__ == "__main__":
    main()
